#!/usr/bin/env bash
# Once per owner: create the key pair that signs OTA images.
#   private key  $KING_OTA_KEY, default ~/.config/king-board/ota_signing_key.pem (never in the repo;
#                back it up: without it a board only takes new firmware over USB)
#   public key   firmware/king_board/ota_pubkey.h, compiled into the firmware (public, committed)
# Refuses to overwrite an existing private key.
set -euo pipefail
cd "$(dirname "$0")/.."
KEY=${KING_OTA_KEY:-$HOME/.config/king-board/ota_signing_key.pem}
PY=.venv-tools/bin/python
[ -x "$PY" ] || { echo "run scripts/setup-dev.sh first"; exit 1; }
CORE="$(arduino-cli config get directories.data)/packages/esp32/hardware/esp32/3.3.10"
[ -f "$CORE/tools/bin_signing.py" ] || { echo "esp32 core 3.3.10 not installed: build once with --profile king_board"; exit 1; }

if [ -e "$KEY" ]; then
  echo "keeping the existing private key: $KEY"
else
  mkdir -p "$(dirname "$KEY")"
  (umask 077 && "$PY" "$CORE/tools/bin_signing.py" --generate-key ecdsa-p256 --out "$KEY" >/dev/null)
  echo "new private key: $KEY  (back it up)"
fi

"$PY" - "$KEY" firmware/king_board/ota_pubkey.h <<'EOF'
import sys
from cryptography.hazmat.primitives import serialization

key = serialization.load_pem_private_key(open(sys.argv[1], "rb").read(), password=None)
pem = key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
body = "\n".join(f'    "{line}\\n"' for line in pem.decode().splitlines())
open(sys.argv[2], "w").write(
    "// GENERATED by scripts/ota-key.sh: the public half of the OTA signing key (ECDSA P-256).\n"
    "// The board accepts only OTA images signed with the matching private key (scripts/ota.sh).\n"
    "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
    f"static const char OTA_PUBKEY_PEM[] =\n{body};\n"
    "static const uint8_t* const OTA_PUBKEY = (const uint8_t*)OTA_PUBKEY_PEM;\n"
    "static const size_t OTA_PUBKEY_LEN = sizeof(OTA_PUBKEY_PEM);  // with the NUL: mbedtls parses PEM as a C string\n"
)
EOF
echo "public key: firmware/king_board/ota_pubkey.h"
