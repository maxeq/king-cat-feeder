#!/usr/bin/env python3
"""
Bundle the pages in web/ into src/net/pages.h, which the firmware serves.

    python3 web/build.py            # rewrite src/net/pages.h
    python3 web/build.py --check    # fail if pages.h is out of date (used in CI)

Static pages are gzipped. cam.html is a template the firmware fills in at runtime,
so it is stored as plain text. The cats page uses web/demo_photos.json if it exists
(not in git: real photos), otherwise placeholder avatars.
"""
import gzip
import json
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parent
OUT = WEB.parent / "src" / "net" / "pages.h"
CATS = ["king", "ginger", "tabby"]
COLORS = {"king": "#8a8f98", "ginger": "#d98a3a", "tabby": "#9b8466"}


def placeholder(name):
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">'
           f'<rect width="100" height="100" fill="{COLORS[name]}"/>'
           f'<text x="50" y="66" font-size="48" font-family="sans-serif" fill="#fff" '
           f'text-anchor="middle">{name[0].upper()}</text></svg>')
    return "data:image/svg+xml," + svg.replace("#", "%23").replace('"', "'")


def cats_page():
    html = (WEB / "cats.html").read_text(encoding="utf-8")
    photos_file = WEB / "demo_photos.json"
    if photos_file.exists():
        photos = json.loads(photos_file.read_text(encoding="utf-8"))
        note = ("Preview with sample data: the photos are real (King, a ginger cat and a tabby), "
                "the numbers are made up.")
    else:
        photos = {c: [placeholder(c)] * 3 for c in CATS}
        note = "Preview with sample data: placeholder photos, made-up numbers."
    return html.replace("__PHOTOS__", json.dumps(photos)).replace("__DEMO_NOTE__", note)


def c_bytes(name, data):
    rows = [",".join(map(str, data[i:i + 24])) for i in range(0, len(data), 24)]
    return (f"const size_t {name}_LEN = {len(data)};\n"
            f"const uint8_t {name}[] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n")


def render():
    index = (WEB / "index.html").read_bytes()
    cam = (WEB / "cam.html").read_text(encoding="utf-8")
    assert ')html"' not in cam
    parts = [
        "// GENERATED by web/build.py from web/*.html. Do not edit by hand.\n",
        "#pragma once\n#include <Arduino.h>\n\n",
        c_bytes("INDEX_GZ", gzip.compress(index, 9, mtime=0)), "\n",
        c_bytes("CATS_GZ", gzip.compress(cats_page().encode("utf-8"), 9, mtime=0)), "\n",
        f'const char CAM_HTML[] PROGMEM = R"html({cam})html";\n',
    ]
    return "".join(parts)


if __name__ == "__main__":
    out = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            sys.exit(f"{OUT.relative_to(WEB.parent)} is out of date: run python3 web/build.py")
        print("pages.h is up to date")
    else:
        OUT.write_text(out, encoding="utf-8")
        print(f"wrote {OUT.relative_to(WEB.parent)} ({len(out) // 1024} KB)")
